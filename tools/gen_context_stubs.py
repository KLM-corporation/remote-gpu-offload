"""Generates proxy_context declarations and default stubs from the SDK's ID3D11DeviceContext.

Usage: python tools/gen_context_stubs.py <path-to-d3d11.h> <out-dir>
Methods listed in IMPLEMENTED are hand-written in src/client/proxy_context.cpp;
every other method receives a benign default (no-op / E_NOTIMPL / 0).
"""
import re
import sys

IMPLEMENTED = {
    "VSSetConstantBuffers", "PSSetConstantBuffers", "PSSetShaderResources", "PSSetShader",
    "PSSetSamplers", "VSSetShader", "DrawIndexed", "Draw", "Map", "Unmap",
    "IASetInputLayout", "IASetVertexBuffers", "IASetIndexBuffer", "IASetPrimitiveTopology",
    "RSSetViewports", "OMSetRenderTargets", "OMSetRenderTargetsAndUnorderedAccessViews",
    "ClearRenderTargetView", "ClearDepthStencilView", "UpdateSubresource", "Flush", "ClearState",
    "OMSetBlendState", "OMSetDepthStencilState", "RSSetState", "RSSetScissorRects",
    "DrawInstanced", "DrawIndexedInstanced", "VSSetShaderResources", "VSSetSamplers",
    "CSSetShader", "CSSetShaderResources", "CSSetUnorderedAccessViews", "CSSetConstantBuffers", "CSSetSamplers",
    "Dispatch", "ClearUnorderedAccessViewUint", "ClearUnorderedAccessViewFloat",
    "CopyResource", "CopySubresourceRegion",
}

src = open(sys.argv[1], encoding="utf-8", errors="replace").read()
start = src.index('MIDL_INTERFACE("c0bfa96c-e089-44fb-8eaf-26f8796190da")')
end = src.index("#ifdef __CRT_UUID_DECL", start)
body = src[start:end]
methods = re.findall(r"virtual\s+(\w+)\s+STDMETHODCALLTYPE\s+(\w+)\(([^)]*)\)\s*=\s*0;", body)

decls, stubs = [], []
for ret, name, args in methods:
    args = " ".join(args.split())
    decls.append(f"    {ret} STDMETHODCALLTYPE {name}({args}) override;")
    if name in IMPLEMENTED:
        continue
    default = {"void": "{}", "HRESULT": "{ return E_NOTIMPL; }",
               "D3D11_DEVICE_CONTEXT_TYPE": "{ return D3D11_DEVICE_CONTEXT_IMMEDIATE; }"}.get(ret, "{ return 0; }")
    # Parameter names are dropped so unused-parameter warnings cannot occur.
    stubs.append(f"{ret} STDMETHODCALLTYPE ProxyD3D11DeviceContext::{name}({args}) {default}")

# Strip parameter names from stubs: keep only the type portion of each argument.
def strip_names(line):
    m = re.match(r"(.*?::\w+\()(.*)(\) .*)", line)
    pre, args, post = m.groups()
    out = []
    for a in filter(None, (x.strip() for x in args.split(","))):
        if not a.endswith("*"):
            # Drop the parameter name but keep any array extent ("const FLOAT x[4]" -> "const FLOAT[4]").
            a = re.sub(r"\s*\b\w+(\[\d*\])?$", lambda m: m.group(1) or "", a)
        out.append(a)
    return pre + ", ".join(out) + post

stubs = [strip_names(s) for s in stubs]
outdir = sys.argv[2]
open(f"{outdir}/proxy_context_decls.inc", "w").write("// Generated by tools/gen_context_stubs.py - do not edit.\n" + "\n".join(decls) + "\n")
open(f"{outdir}/proxy_context_stubs.inc", "w").write("// Generated by tools/gen_context_stubs.py - do not edit.\n" + "\n".join(stubs) + "\n")
print(len(methods), "methods,", len(stubs), "stubs")
